import math

def circle_area(r):
    return math.pi * r * r

def circle_circumference(r):
    return 2 * math.pi * r

def square_area(a):
    return a * a

def square_circumference(a):
    return 4 * a

def rectangle_area(l, w):
    return l * w

def rectangle_circumference(l, w):
    return 2 * (l + w)